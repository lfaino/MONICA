"""Web interface for MONICA: submit runs from a browser, follow them, download results.

One container, no broker and no database: jobs are directories under
MONICA_JOBS, each holding the parameters, the log and every file the pipeline
produced, and a single worker thread runs them one at a time.

The advanced part of the form is generated by reading the argument parser of
monica_v5.py at request time, so adding or renaming an option in the pipeline
changes the web form with no registration step.
"""

import json
import os
import shutil
import signal
import subprocess
import sys
import threading
import time
import uuid
from argparse import SUPPRESS
from datetime import datetime, timezone
from pathlib import Path
from queue import Queue

from fastapi import FastAPI, Form, HTTPException, Request
from fastapi.responses import (FileResponse, HTMLResponse, PlainTextResponse,
                               RedirectResponse)
from fastapi.templating import Jinja2Templates

MONICA_SCRIPT = os.environ.get("MONICA_SCRIPT", "/opt/monica/monica_v5.py")
JOBS_DIR = Path(os.environ.get("MONICA_JOBS", "/jobs"))
SEQ_ROOT = Path(os.environ.get("MONICA_SEQ_ROOT", "/mnt/data3ZEUSPV/SequenceData"))
BLASTDB_DIR = Path(os.environ.get("BLASTDB", "/mnt/dataQNAP/blastdb"))
DEFAULT_EMAIL = os.environ.get("MONICA_DEFAULT_EMAIL", "")
DEFAULT_THREADS = os.environ.get("MONICA_DEFAULT_THREADS", "16")
SCAN_DEPTH = int(os.environ.get("MONICA_SCAN_DEPTH", "7"))
SITE_NAME = os.environ.get("MONICA_SITE_NAME", "MONICA")

# Fields the simple part of the form takes care of; everything else in the
# parser is offered under "advanced options".
SIMPLE_DESTS = {"barcode", "folder_fastq", "email", "output", "database",
                "database_external", "help", "version"}
HIDDEN_DESTS = {"temp", "working_directory", "update_ete", "cleanup", "keep_temp",
                "log_file", "taxonomy_db", "retmax", "search"}

sys.path.insert(0, str(Path(MONICA_SCRIPT).parent))
import monica_v5  # noqa: E402  (after sys.path is set)

app = FastAPI(title=SITE_NAME)
templates = Jinja2Templates(directory=str(Path(__file__).parent / "templates"))

JOB_QUEUE: "Queue[str]" = Queue()
RUNNING: dict = {}          # job_id -> subprocess.Popen
_runs_cache: dict = {"when": 0.0, "value": []}


# --------------------------------------------------------------------------- #
# Inputs offered by the form
# --------------------------------------------------------------------------- #


def sequencing_runs() -> list:
    """Directories holding basecalled reads, as (label, path) pairs.

    A MinION run buries them several levels deep, so the tree is walked looking
    for `fastq_pass` (or `fastq`) directories and the result is cached briefly:
    unlike a registered form, the list is rebuilt while the page is served, so a
    run finished five minutes ago is already selectable.
    """
    if time.time() - _runs_cache["when"] < 60:
        return _runs_cache["value"]
    found = []
    if SEQ_ROOT.is_dir():
        root_depth = len(SEQ_ROOT.parts)
        for current, dirnames, filenames in os.walk(SEQ_ROOT):
            path = Path(current)
            if len(path.parts) - root_depth >= SCAN_DEPTH:
                dirnames[:] = []
                continue
            # A run is a directory holding barcode sub-directories (any layout),
            # or the fastq_pass of a MinION run with the reads directly in it.
            has_barcodes = any(name.lower().startswith("barcode") for name in dirnames)
            is_fastq_dir = path.name in ("fastq_pass", "fastq") and any(
                name.endswith((".fastq", ".fastq.gz", ".fq", ".fq.gz")) for name in filenames)
            if has_barcodes or is_fastq_dir:
                dirnames[:] = [name for name in dirnames
                               if not name.lower().startswith("barcode")]
                relative = path.relative_to(SEQ_ROOT)
                found.append((str(relative) if relative.parts else path.name, str(path)))
    found.sort(key=lambda item: item[0], reverse=True)
    _runs_cache.update(when=time.time(), value=found)
    return found


def barcodes_of(folder: str) -> list:
    """Barcode sub-directories of a run, so the user can tick them."""
    path = Path(folder)
    if not path.is_dir():
        return []
    return sorted(child.name for child in path.iterdir()
                  if child.is_dir() and child.name.lower().startswith("barcode"))


def databases() -> list:
    """Databases offered by the form, as (label, flag, value).

    The pipeline only accepts its built-in names under `-d`; anything else found
    in the database directory is passed as an external database, so a user who
    copied their own database in just picks it from the same list.
    """
    builtin = list(getattr(monica_v5, "DATABASE_CHOICES", []))
    entries = [(name, "-d", name) for name in builtin]
    known = {name for name in builtin}
    known |= {name[:-4] for name in builtin if name.endswith(".nal")}
    if BLASTDB_DIR.is_dir():
        for entry in sorted(BLASTDB_DIR.iterdir()):
            if entry.suffix == ".nal":
                stem = entry.stem
            elif entry.suffix == ".nin":
                stem = entry.name[:-4].split(".0")[0]
            else:
                continue
            if stem in known:
                continue
            known.add(stem)
            entries.append((stem, "-dbe", str(BLASTDB_DIR / stem)))
    return entries


def advanced_fields() -> list:
    """Form fields derived from the pipeline's own argument parser."""
    fields = []
    for action in monica_v5.build_parser()._actions:
        if action.dest in SIMPLE_DESTS or action.dest in HIDDEN_DESTS:
            continue
        if not action.option_strings or action.help == SUPPRESS:
            continue
        kind = "checkbox" if action.const is True or action.nargs == 0 else "text"
        fields.append({
            "dest": action.dest,
            "flag": action.option_strings[-1],
            "help": " ".join((action.help or "").split()),
            "default": "" if action.default in (None, SUPPRESS) else action.default,
            "choices": list(action.choices) if action.choices else None,
            "kind": "select" if action.choices else kind,
        })
    fields.sort(key=lambda field: field["dest"])
    return fields


