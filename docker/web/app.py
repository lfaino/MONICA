def job_dir(job_id: str) -> Path:
    path = (JOBS_DIR / job_id).resolve()
    if not str(path).startswith(str(JOBS_DIR.resolve())) or not path.is_dir():
        raise HTTPException(status_code=404, detail="job not found")
    return path


def read_state(path: Path) -> dict:
    try:
        return json.loads((path / "state.json").read_text())
    except Exception:
        return {"id": path.name, "status": "unknown", "name": path.name}


def write_state(path: Path, **changes) -> dict:
    state = read_state(path)
    state.update(changes)
    (path / "state.json").write_text(json.dumps(state, indent=2))
    return state


def all_jobs() -> list:
    jobs = [read_state(path) for path in JOBS_DIR.iterdir() if path.is_dir()]
    return sorted(jobs, key=lambda state: state.get("submitted", ""), reverse=True)


def result_files(path: Path) -> list:
    """Files produced by the run, newest first, excluding our own bookkeeping."""
    skip = {"state.json", "monica.log"}
    files = [entry for entry in path.iterdir() if entry.is_file() and entry.name not in skip]
    files.sort(key=lambda entry: entry.name)
    return [{"name": entry.name, "size": entry.stat().st_size} for entry in files]


def worker() -> None:
    """Run queued jobs one at a time, in the order they were submitted."""
    while True:
        job_id = JOB_QUEUE.get()
        path = JOBS_DIR / job_id
        state = read_state(path)
        if state.get("status") == "cancelled":
            JOB_QUEUE.task_done()
            continue
        write_state(path, status="running",
                    started=datetime.now(timezone.utc).isoformat(timespec="seconds"))
        with open(path / "monica.log", "ab", buffering=0) as log:
            process = subprocess.Popen(
                state["command"], cwd=path, stdout=log, stderr=subprocess.STDOUT,
                start_new_session=True)
            RUNNING[job_id] = process
            code = process.wait()
            RUNNING.pop(job_id, None)
        final = read_state(path).get("status")
        write_state(path,
                    status="cancelled" if final == "cancelling" else
                           ("done" if code == 0 else "failed"),
                    returncode=code,
                    finished=datetime.now(timezone.utc).isoformat(timespec="seconds"))
        JOB_QUEUE.task_done()


@app.on_event("startup")
def start_worker() -> None:
    JOBS_DIR.mkdir(parents=True, exist_ok=True)
    for path in JOBS_DIR.iterdir():
        if path.is_dir() and read_state(path).get("status") in ("running", "cancelling"):
            # The container restarted while this job was running.
            write_state(path, status="interrupted")
        elif path.is_dir() and read_state(path).get("status") == "queued":
            JOB_QUEUE.put(path.name)
    threading.Thread(target=worker, daemon=True).start()


