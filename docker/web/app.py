@app.get("/", response_class=HTMLResponse)
def index(request: Request):
    return templates.TemplateResponse(request, "index.html", {
        "request": request, "site": SITE_NAME, "runs": sequencing_runs(),
        "databases": databases(), "advanced": advanced_fields(),
        "default_email": DEFAULT_EMAIL, "default_threads": DEFAULT_THREADS,
        "jobs": all_jobs()[:10],
    })


@app.get("/barcodes", response_class=HTMLResponse)
def barcodes(folder: str):
    """Barcode list of a run, fetched by the page when a run is chosen."""
    names = barcodes_of(folder)
    if not names:
        return HTMLResponse('<p class="muted">Nessun barcode trovato in questa cartella.</p>')
    boxes = "".join(
        f'<label class="barcode"><input type="checkbox" name="barcodes" value="{name}"> {name}</label>'
        for name in names)
    return HTMLResponse(
        f'<p><a href="#" onclick="setAll(true);return false">tutti</a> · '
        f'<a href="#" onclick="setAll(false);return false">nessuno</a></p>{boxes}')


@app.post("/run")
async def submit(request: Request):
    form = await request.form()
    folder = (form.get("folder_fastq_choice") or "").strip() or (form.get("folder_fastq") or "").strip()
    chosen = [value for value in form.getlist("barcodes")]
    typed = (form.get("barcode") or "").strip()
    barcode = ",".join(chosen) if chosen else typed
    email = (form.get("email") or "").strip() or DEFAULT_EMAIL
    name = (form.get("name") or "").strip() or datetime.now().strftime("run_%Y%m%d_%H%M")
    database = (form.get("database") or "").strip()
    external = (form.get("database_external") or "").strip()

    errors = []
    if not folder or not Path(folder).is_dir():
        errors.append("La cartella delle reads non esiste o non è stata indicata.")
    if not barcode:
        errors.append("Seleziona almeno un barcode (o scrivilo a mano, es. barcode01-12).")
    if not email:
        errors.append("L'indirizzo email è richiesto da blast.")
    if not database and not external:
        errors.append("Scegli un database.")
    if errors:
        return templates.TemplateResponse(request, "index.html", {
            "request": request, "site": SITE_NAME, "runs": sequencing_runs(),
            "databases": databases(), "advanced": advanced_fields(),
            "default_email": DEFAULT_EMAIL, "default_threads": DEFAULT_THREADS,
            "jobs": all_jobs()[:10], "errors": errors,
        }, status_code=400)

    command = [sys.executable, MONICA_SCRIPT,
               "--folder_fastq", folder, "--barcode", barcode,
               "-e", email, "-o", name]
    if external:
        command += ["-dbe", external]
    else:
        flag, value = next(((flag, value) for label, flag, value in databases()
                            if label == database), ("-d", database))
        command += [flag, value]

    # Advanced options: only those the user actually changed.
    for field in advanced_fields():
        value = form.get(field["dest"])
        if field["kind"] == "checkbox":
            if value:
                command.append(field["flag"])
        elif value not in (None, "") and str(value) != str(field["default"]):
            command += [field["flag"], str(value)]

    job_id = datetime.now().strftime("%Y%m%d-%H%M%S-") + uuid.uuid4().hex[:6]
    path = JOBS_DIR / job_id
    path.mkdir(parents=True)
    write_state(path, id=job_id, name=name, status="queued", command=command,
                folder=folder, barcode=barcode,
                database=external or database,
                submitted=datetime.now(timezone.utc).isoformat(timespec="seconds"))
    (path / "monica.log").touch()
    JOB_QUEUE.put(job_id)
    return RedirectResponse(f"/jobs/{job_id}", status_code=303)


@app.get("/jobs", response_class=HTMLResponse)
def jobs(request: Request):
    return templates.TemplateResponse(request, "jobs.html", {
        "request": request, "site": SITE_NAME, "jobs": all_jobs()})


@app.get("/jobs/{job_id}", response_class=HTMLResponse)
def job_page(request: Request, job_id: str):
    path = job_dir(job_id)
    state = read_state(path)
    log = ""
    log_path = path / "monica.log"
    if log_path.exists():
        with open(log_path, "rb") as handle:          # last 8 kB are enough
            handle.seek(max(0, log_path.stat().st_size - 8192))
            log = handle.read().decode(errors="replace")
    return templates.TemplateResponse(request, "job.html", {
        "request": request, "site": SITE_NAME, "job": state, "log": log,
        "files": result_files(path),
        "refresh": state.get("status") in ("queued", "running", "cancelling"),
        "command": " ".join(state.get("command", [])),
    })


@app.get("/jobs/{job_id}/files/{filename}")
def download(job_id: str, filename: str):
    path = job_dir(job_id) / filename
    if ".." in filename or "/" in filename or not path.is_file():
        raise HTTPException(status_code=404, detail="file not found")
    inline = path.suffix in (".html", ".pdf", ".txt", ".json")
    return FileResponse(path, filename=None if inline else filename,
                        media_type="text/html" if path.suffix == ".html" else None)


@app.get("/jobs/{job_id}/log", response_class=PlainTextResponse)
def full_log(job_id: str):
    return (job_dir(job_id) / "monica.log").read_text(errors="replace")


@app.post("/jobs/{job_id}/cancel")
def cancel(job_id: str):
    path = job_dir(job_id)
    state = read_state(path)
    if state.get("status") == "queued":
        write_state(path, status="cancelled")
    elif state.get("status") == "running":
        write_state(path, status="cancelling")
        process = RUNNING.get(job_id)
        if process is not None:
            os.killpg(os.getpgid(process.pid), signal.SIGTERM)
    return RedirectResponse(f"/jobs/{job_id}", status_code=303)


@app.post("/jobs/{job_id}/delete")
def delete(job_id: str):
    path = job_dir(job_id)
    if read_state(path).get("status") in ("running", "cancelling"):
        raise HTTPException(status_code=409, detail="the job is still running")
    shutil.rmtree(path)
    return RedirectResponse("/jobs", status_code=303)


@app.get("/health", response_class=PlainTextResponse)
def health():
    return "ok"
